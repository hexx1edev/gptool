/// Build and write a protective MBR sector at LBA 0.
pub fn write_protective_mbr(file: &mut File, total_sectors: u64) -> Result<()> {
    let mut mbr = [0u8; 512];

    // Bootstrap code (440 bytes)
    mbr[..440].copy_from_slice(&BOOTSECT_CODE);

    // Disk signature (4 bytes) - leave zero
    // Reserved (2 bytes) - leave zero

    // Partition entry 1 at offset 446 — protective GPT partition
    let pe = 446;
    mbr[pe] = 0x00; // Status: not bootable
    // CHS of first absolute sector
    mbr[pe + 1] = 0x00; // Head
    mbr[pe + 2] = 0x02; // Sector (1-based, sector 2)
    mbr[pe + 3] = 0x00; // Cylinder
    mbr[pe + 4] = 0xEE; // Type: GPT protective
    // CHS of last absolute sector
    mbr[pe + 5] = 0xFF;
    mbr[pe + 6] = 0xFF;
    mbr[pe + 7] = 0xFF;
    // First LBA = 1
    mbr[pe + 8..pe + 12].copy_from_slice(&1u32.to_le_bytes());
    // Number of sectors (capped at u32::MAX for >2TiB disks)
    let part_sectors = std::cmp::min(total_sectors - 1, u32::MAX as u64) as u32;
    mbr[pe + 12..pe + 16].copy_from_slice(&part_sectors.to_le_bytes());

    // Partition entries 2-4 remain zeroed

    // Boot signature
    mbr[510] = 0x55;
    mbr[511] = 0xAA;

    file.seek(SeekFrom::Start(0))?;
    file.write_all(&mbr)?;
    Ok(())
}
